-- Items on hold (26/11/2026). The office switches an item off on the cut sheet
-- (say its size isn't confirmed yet) and its pieces come off until it is back on.
--   saw_jobs.held_items  the quote items on hold, e.g. ["21967/17"]
--   saw_bars.skipped     positions in "cuts" that were on hold when the bar was
--                        marked cut, so they come back as "still to cut" later
-- (saw_job_summary was dropped and re-created after this so it carries held_items.)
alter table public.saw_jobs add column if not exists held_items jsonb not null default '[]'::jsonb;
alter table public.saw_bars add column if not exists skipped jsonb not null default '[]'::jsonb;

-- Loading straight from vQuote (26/11/2026).
-- vquote_cutplans: one row per quote, filled by esp-sync\vquote-cutplan-sync.ps1 on the
-- office sync machine (service key). "bars" is the saved cutting plan in the same shape
-- as saw_bars rows; "items" is [{pos,type,descr}]. Signed-in staff read; nobody writes
-- from the portal.
-- vquote_cutplan_requests: the Saw Bench asks for a quote number that isn't there yet;
-- the sync copies it on its next run and stamps done_at/result.
create table if not exists public.vquote_cutplans (
  quote_num    integer primary key,
  quote_id     integer,
  quote_vers   integer,
  job_num      text,
  quote_title  text,
  last_modify  date,
  items        jsonb not null default '[]'::jsonb,
  bars         jsonb not null default '[]'::jsonb,
  bar_count    integer not null default 0,
  piece_count  integer not null default 0,
  synced_at    timestamptz not null default now()
);
alter table public.vquote_cutplans enable row level security;
revoke all on public.vquote_cutplans from anon;
revoke insert, update, delete, truncate on public.vquote_cutplans from authenticated;
grant select on public.vquote_cutplans to authenticated;
create policy "staff read vquote cutplans" on public.vquote_cutplans for select to authenticated using (public.is_staff());

create table if not exists public.vquote_cutplan_requests (
  id            bigint generated by default as identity primary key,
  quote_num     integer not null,
  requested_by  text,
  requested_at  timestamptz not null default now(),
  done_at       timestamptz,
  result        text
);
create index if not exists vquote_cutplan_requests_open_idx on public.vquote_cutplan_requests (quote_num) where done_at is null;
alter table public.vquote_cutplan_requests enable row level security;
revoke all on public.vquote_cutplan_requests from anon;
revoke update, delete, truncate on public.vquote_cutplan_requests from authenticated;
grant select, insert on public.vquote_cutplan_requests to authenticated;
create policy "staff read cutplan requests" on public.vquote_cutplan_requests for select to authenticated using (public.is_staff());
create policy "staff ask for a cutplan" on public.vquote_cutplan_requests for insert to authenticated with check (public.is_staff() and done_at is null);

