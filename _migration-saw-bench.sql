-- One row per job with its progress, for the job list (counts done in the
-- database so a big job never hits the 1000-row page limit).
create or replace view public.saw_job_summary with (security_invoker = true) as
select j.*,
  (select count(*) from public.saw_bars b where b.job_id = j.id)::int                          as bars_total,
  (select count(*) from public.saw_bars b where b.job_id = j.id and b.done)::int               as bars_done,
  (select count(*) from public.saw_pick_lines p where p.job_id = j.id)::int                    as pick_total,
  (select count(*) from public.saw_pick_lines p where p.job_id = j.id and p.qty_in_stock is not null)::int as pick_counted,
  (select coalesce(sum(greatest(p.qty_needed - p.qty_in_stock, 0)), 0) from public.saw_pick_lines p
     where p.job_id = j.id and p.qty_in_stock is not null)::int                                as bars_short
from public.saw_jobs j;
revoke all on public.saw_job_summary from anon;
grant select on public.saw_job_summary to authenticated;

