-- =============================================================================
-- Factory Portal — Saw Bench (cut sheets and pick sheets on the saw screen)
-- =============================================================================
-- Applied to the live database (souwlbqovhhmjrfpxunv) on 26/11/2026. Kept here
-- for the record.
--
-- The office drops two vQuote reports onto the Saw Bench page:
--   EXTRUSION BAR SUMMARY REPORT  -> saw_pick_lines (one row per extrusion/length)
--   OPTIMISED CUTTING PLAN        -> saw_bars       (one row per bar, cuts in JSON)
-- The sawyer counts stock against the pick lines and ticks bars off as cut.
--
-- Signed-in staff can read and update. Only supervisors and above can load or
-- replace a job's sheets; only managers can delete a job. Nothing is readable
-- without signing in.
-- =============================================================================
create table if not exists public.saw_jobs (
  id              bigint generated by default as identity primary key,
  quote_num       text,
  quote_version   text,
  job_number      text,
  title           text,
  customer        text,
  status          text not null default 'Active' check (status in ('Active','Done')),
  pick_pdf        text,                       -- path in the saw-sheets bucket
  cut_pdf         text,
  pick_report_at  text,                       -- Date/Time printed on the report
  cut_report_at   text,
  pick_sent_at    timestamptz,                -- sawyer tapped "Send to office"
  pick_sent_by    text,
  pick_note       text,
  ordered_at      timestamptz,                -- office marked the shortages ordered
  ordered_by      text,
  created_at      timestamptz not null default now(),
  created_by_name text,
  updated_at      timestamptz not null default now()
);
create index if not exists saw_jobs_quote_idx on public.saw_jobs (quote_num);

create table if not exists public.saw_pick_lines (
  id            bigint generated by default as identity primary key,
  job_id        bigint not null references public.saw_jobs(id) on delete cascade,
  sort_order    integer not null default 0,
  extrusion     text not null,
  description   text,
  finish        text,
  bar_length_mm integer,
  qty_needed    integer not null,
  qty_in_stock  integer,                      -- null = not counted yet
  checked_by    text,
  checked_at    timestamptz
);
create index if not exists saw_pick_lines_job_idx on public.saw_pick_lines (job_id, sort_order);

create table if not exists public.saw_bars (
  id            bigint generated by default as identity primary key,
  job_id        bigint not null references public.saw_jobs(id) on delete cascade,
  sort_order    integer not null default 0,
  extrusion     text not null,
  description   text,
  finish        text,
  bar_length_mm integer,
  bar_no        integer,
  waste_mm      integer,
  cuts          jsonb not null default '[]'::jsonb,   -- [{l,size,r,qty,item}]
  done          boolean not null default false,
  done_by       text,
  done_at       timestamptz
);
create index if not exists saw_bars_job_idx on public.saw_bars (job_id, sort_order);

alter table public.saw_jobs       enable row level security;
alter table public.saw_pick_lines enable row level security;
alter table public.saw_bars       enable row level security;
