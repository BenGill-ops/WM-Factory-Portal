-- Electronic defect reporting for all fabricators. Replaces the paper
-- "Defect report form - all fabricators" on the factory floor.
--
-- Visibility: managers see every defect; a fabricator sees only defects they
-- raised, found, or did the work on.

-- Helper: the signed-in user's team_members.id
create or replace function public.my_member_id() returns bigint
  language sql stable security definer set search_path to 'public'
as $$
  select id from team_members
  where auth_user_id = auth.uid() and is_active = true
  limit 1
$$;

create table if not exists public.defect_reports (
  id                    bigint generated by default as identity primary key,
  defect_no             text,                                 -- DEF-YYYY-NNN
  found_at              timestamptz not null default now(),
  job_number            text,
  customer              text,
  stage                 text,                                 -- At the bench / Next stage / Before loading / On site / By the client
  defect_type           text,
  description           text,
  units_affected        integer default 1,
  repeated_across_job   boolean default false,
  repeat_count          integer,
  rework_minutes        integer,
  materials_cost        numeric(10,2),
  reached_client        boolean default false,
  self_reported         boolean default false,                -- reported by the person who did the work, on the day
  prevention            text,                                 -- anything that would have caught it earlier
  photos                jsonb default '[]'::jsonb,            -- [{url,name}] in the ncr-photos bucket under defects/
  status                text default 'Open',
  found_by_id           bigint references public.team_members(id),
  found_by_name         text,
  work_by_id            bigint not null references public.team_members(id),
  work_by_name          text,
  closed_at             timestamptz,
  closed_by_id          bigint references public.team_members(id),
  closed_by_name        text,
  closure_note          text,
  created_at            timestamptz default now(),
  created_by_id         bigint references public.team_members(id),
  created_by_name       text
);

alter table public.defect_reports enable row level security;

create policy defect_select on public.defect_reports for select to authenticated
  using (
    public.is_manager()
    or created_by_id = public.my_member_id()
    or found_by_id   = public.my_member_id()
    or work_by_id    = public.my_member_id()
  );

create policy defect_insert on public.defect_reports for insert to authenticated
  with check (public.is_staff());

create policy defect_update on public.defect_reports for update to authenticated
  using (public.is_manager());

create policy defect_delete on public.defect_reports for delete to authenticated
  using (public.is_manager());
